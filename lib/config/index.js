  /**
   * Accept any configuration passed back from the server. Will log all
   * recognized, unsupported, and unknown parameters.
   *
   * @param {object} json The config blob sent by New Relic.
   * @param {boolean} parsingAgentConfig Flag indicating that the inner
   * `agent_config` block from the server provided data is being processed.
   * Initially, the `json` blob is all top-level settings with an `agent_config`
   * top-level property. The spec dictates that `agent_config` contains the
   * actual server side settings, but `high_security` is _only_ a top-level
   * property and is not included in the `agent_config` block. When we parse
   * the data in {@link #fromServer}, and we reach the `agent_config` block,
   * we pass that data back to this method and need a way to indicate it as
   * such. Thus, the `parsingAgentConfig` parameter.
   *
   * @fires Config#agent_enabled When there is a conflict between the local
   * setting of high security mode and what the New Relic server has returned.
   * @fires Config#change
   */
  onConnect(json, parsingAgentConfig = false) {
    json = json || Object.create(null)

    if (this.high_security && parsingAgentConfig !== true && !json.high_security) {
      this.agent_enabled = false
      this.emit('agent_enabled', false)
      return
    }

    const keys = Object.keys(json)
    if (keys.length === 0) return

    for (const key of keys) {
      this.#setFromServer(json, key)
    }

    this.emit('change', this)
  }

