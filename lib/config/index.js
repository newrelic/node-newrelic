  /**
   * Compares the labels list to the application logging excluded label list and
   * removes any labels that need to be excluded. Each label is then
   * prefixed with `tags.`.
   */
  #setApplicationLoggingLabels() {
    if (this.application_logging.forwarding.labels.enabled === false) {
      return
    }

    this.application_logging.forwarding.labels.exclude =
      this.application_logging.forwarding.labels.exclude.map((k) => k.toLowerCase())
    const exclude = this.application_logging.forwarding.labels.exclude
    const filteredLabels = {}
    for (const label of this.parsedLabels) {
      if (exclude.includes(label.label_type.toLowerCase()) !== false) {
        continue
      }
      // The parsed label is not listed in the "exclude labels" set, so
      // we add it to the set of labels that will be applied.
      filteredLabels[`tags.${label.label_type}`] = label.label_value
    }

    this.loggingLabels = filteredLabels
  }

